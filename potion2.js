const keranjang = {
  _detailPotion: [],

  get detailPotion() {
    const fil = this._detailPotion.filter((poti) => poti.stok > 0);
    this._detailPotion = fil;
    return this._detailPotion;
  },

  get totalPotion() {
    if (this.detailPotion.length < 1) {
      return 0;
    }
    const total = this.detailPotion.map((nam) => nam.stok);
    return total.reduce((total, stok) => total + stok);
  },

  get totalHargaPotion() {
    if (this.detailPotion.length < 1) {
      return 0;
    }
    const total = this.detailPotion.map((nam) => nam.stok * nam.harga);
    return total.reduce((total, stok) => total + stok);
  },

  button(data, nama) {
    const draf = this.detailPotion.find((item) => item.nama === data);
    const toko = potionPedagang._potionList.find((de) => de.nama === data);

    if (nama === "buang") {
      draf.stok--;
    } else if (nama === "nambah") {
      if (
        toko.stok > draf.stok &&
        this.totalHargaPotion + draf.harga <= potionPetualang.saldo
      ) {
        draf.stok++;
      }
    } else {
      draf.stok = 0;
    }

    tampilkanPotionBeli(potionPedagang._potionList);
    tampilkanKeranjang(this.detailPotion);
    totalPotion.textContent = this.totalPotion;
    totalHargaPotion.textContent = this.totalHargaPotion;
    shoppingcardspan.textContent = this.totalPotion;
  },

  nambahPotion(naugh) {
    const data = this._detailPotion.find((de) => de.nama === naugh.nama);

    const toko = potionPedagang._potionList.find(
      (de) => de.nama === naugh.nama,
    );

    // kunci untuk nentuin data undefined (data => data !== undefined)
    if (data && data.stok >= toko.stok) return;
    const totalHargaBaru = this.totalHargaPotion + naugh.harga;
    if (totalHargaBaru > potionPetualang.saldo) return;

    if (data === undefined) {
      this._detailPotion.push({
        nama: naugh.nama,
        gambar: naugh.gambar,
        harga: naugh.harga,
        stok: 1,
      });
    } else {
      data.stok++;
    }

    tampilkanPotionBeli(potionPedagang.potionList);
    tampilkanKeranjang(this.detailPotion);
    totalPotion.textContent = this.totalPotion;
    totalHargaPotion.textContent = this.totalHargaPotion;
    shoppingcardspan.textContent = this.totalPotion;
  },

  checkout() {
    keranjang.detailPotion.forEach((keran) => {
      const petualang = potionPetualang._potionList.find(
        (pot) => pot.nama === keran.nama,
      );
      const pedagang = potionPedagang._potionList.find(
        (pot) => pot.nama === keran.nama,
      );

      petualang.stok += keran.stok;
      pedagang.stok -= keran.stok;
    });

    potionPetualang.saldo -= this.totalHargaPotion;
    statusSaldo.textContent = potionPetualang.saldo;
    keranjang._detailPotion = [];
    tampilkanKeranjang(keranjang.detailPotion);
    tampilkanPotionBeli(potionPedagang.potionList);
    tampilkanPotionHome(potionPetualang.potionList);
    totalPotion.textContent = keranjang.totalPotion;
    totalHargaPotion.textContent = keranjang.totalHargaPotion;
    shoppingcardspan.textContent = keranjang.totalPotion;
  },
};

