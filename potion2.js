// filter inventori di kedua halaman (home dan beli)
const fungsiFilter = (drop, option, listpotion) => {
  let daftarPotion = [...listpotion];
  let prioritas = [];

  switch (option) {
    case "default":
      if (drop === filterPotionHome) {
        tampilkanPotionHome(daftarPotion);
      } else {
        tampilkanPotionBeli(daftarPotion);
      }

      break;
    case "termurah":
      daftarPotion.sort((a, b) => a.harga - b.harga);
      if (drop === filterPotionHome) {
        stokPotionInventory = buatFilterHome(daftarPotion, "harga", "");
      } else {
        stokPotionInventory = buatFilterBeli(daftarPotion, "harga");
      }
      break;
    case "termahal":
      daftarPotion.sort((a, b) => b.harga - a.harga);
      if (drop === filterPotionHome) {
        stokPotionInventory = buatFilterHome(daftarPotion, "harga", "");
      } else {
        stokPotionInventory = buatFilterBeli(daftarPotion, "harga");
      }
      break;
    case "terbanyak":
      daftarPotion.sort((a, b) => b.stok - a.stok);
      if (drop === filterPotionHome) {
        stokPotionInventory = buatFilterHome(daftarPotion, "stok", "x ");
      } else {
        stokPotionInventory = buatFilterBeli(daftarPotion, "stok");
      }
      break;
    case "tersedikit":
      daftarPotion.sort((a, b) => a.stok - b.stok);
      if (drop === filterPotionHome) {
        stokPotionInventory = buatFilterHome(daftarPotion, "stok", "x ");
      } else {
        stokPotionInventory = buatFilterBeli(daftarPotion, "stok");
      }
      break;
    case "buff":
      prioritas = ["B", "C", "D"];
      daftarPotion.sort(
        (a, b) => prioritas.indexOf(a.js) - prioritas.indexOf(b.js),
      );
      if (drop === filterPotionHome) {
        stokPotionInventory = buatFilterHome(daftarPotion, "js", "");
      } else {
        stokPotionInventory = buatFilterBeli(daftarPotion, "jenis");
      }
      break;
    case "damage":
      prioritas = ["D", "B", "C"];
      daftarPotion.sort(
        (a, b) => prioritas.indexOf(a.js) - prioritas.indexOf(b.js),
      );
      if (drop === filterPotionHome) {
        stokPotionInventory = buatFilterHome(daftarPotion, "js", "");
      } else {
        stokPotionInventory = buatFilterBeli(daftarPotion, "jenis");
      }
      break;
    case "crowdControl":
      prioritas = ["C", "B", "D"];
      daftarPotion.sort(
        (a, b) => prioritas.indexOf(a.js) - prioritas.indexOf(b.js),
      );
      if (drop === filterPotionHome) {
        stokPotionInventory = buatFilterHome(daftarPotion, "js", "");
      } else {
        stokPotionInventory = buatFilterBeli(daftarPotion, "jenis");
      }
      break;
    case "darkElixir":
      prioritas = ["DE", "E"];
      daftarPotion.sort(
        (a, b) => prioritas.indexOf(a.ts) - prioritas.indexOf(b.ts),
      );
      if (drop === filterPotionHome) {
        stokPotionInventory = buatFilterHome(daftarPotion, "ts", "");
      } else {
        stokPotionInventory = buatFilterBeli(daftarPotion, "tipe");
      }
      break;
    case "elixir":
      prioritas = ["E", "DE"];
      daftarPotion.sort(
        (a, b) => prioritas.indexOf(a.ts) - prioritas.indexOf(b.ts),
      );
      if (drop === filterPotionHome) {
        stokPotionInventory = buatFilterHome(daftarPotion, "ts", "");
      } else {
        stokPotionInventory = buatFilterBeli(daftarPotion, "tipe");
      }
      break;
  }
};

